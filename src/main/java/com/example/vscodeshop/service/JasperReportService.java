package com.example.vscodeshop.service;

import com.example.vscodeshop.model.LoginLog;
import com.example.vscodeshop.model.Product;
import com.example.vscodeshop.repository.ProductRepository;
import net.sf.jasperreports.engine.*;
import net.sf.jasperreports.engine.data.JRBeanCollectionDataSource;
import org.springframework.core.io.ClassPathResource;
import org.springframework.stereotype.Service;

import java.io.InputStream;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.Comparator;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

@Service
public class JasperReportService {

    private final LoginLogService loginLogService;
    private final ProductRepository productRepository;

    public JasperReportService(LoginLogService loginLogService, ProductRepository productRepository) {
        this.loginLogService = loginLogService;
        this.productRepository = productRepository;
    }

    public byte[] createTestPdf() {
        try (InputStream input = new ClassPathResource("reports/test-report.jrxml").getInputStream()) {
            JasperReport report = JasperCompileManager.compileReport(input);

            Map<String, Object> params = new HashMap<>();
            params.put("REPORT_TITLE", "StyleShop - JasperReports Test");
            params.put("GENERATED_AT", LocalDateTime.now().format(
                    DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss")));
            params.put("ARCHITECTURE", "React 5173 -> Spring Boot 8080 -> MyBatis XML -> MySQL");
            params.put("STATUS_TEXT", "PDF generation succeeded");
            params.put("NOTE_TEXT", "This is a test report generated by JasperReports 7.0.1.");

            JasperPrint print = JasperFillManager.fillReport(report, params, new JREmptyDataSource());
            return JasperExportManager.exportReportToPdf(print);
        } catch (Exception e) {
            throw new IllegalStateException("JasperReports PDF generation failed", e);
        }
    }

    public byte[] createLoginHistoryPdf() {
        try (InputStream input = new ClassPathResource("reports/login-history-report.jrxml").getInputStream()) {
            JasperReport report = JasperCompileManager.compileReport(input);

            List<LoginLog> rows = loginLogService.findAll();

            Map<String, Object> params = new HashMap<>();
            params.put("REPORT_TITLE", "StyleShop 登入紀錄清單 (JasperReports 匯出)");
            params.put("GENERATED_AT", LocalDateTime.now().format(
                    DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss")));
            params.put("TOTAL_COUNT", rows.size());

            JRBeanCollectionDataSource dataSource = new JRBeanCollectionDataSource(rows);
            JasperPrint print = JasperFillManager.fillReport(report, params, dataSource);
            return JasperExportManager.exportReportToPdf(print);
        } catch (Exception e) {
            throw new IllegalStateException("登入紀錄 PDF 產生失敗", e);
        }
    }
    public byte[] createProductListPdf() {
        try (InputStream input = new ClassPathResource("reports/product-list-report.jrxml").getInputStream()) {
            JasperReport report = JasperCompileManager.compileReport(input);

            List<Product> rows = productRepository.findAll();

            // 商品 PDF 依價格由低到高排序；價格相同時再依商品編號由小到大。
            rows.sort(
                    Comparator.comparing(
                                    Product::getPrice,
                                    Comparator.nullsLast(Integer::compareTo))
                            .thenComparing(
                                    Product::getId,
                                    Comparator.nullsLast(Long::compareTo))
            );

            Map<String, Object> params = new HashMap<>();
            params.put("REPORT_TITLE", "StyleShop 管理商品清單 (JasperReports 匯出)");
            params.put("GENERATED_AT", LocalDateTime.now().format(
                    DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss")));
            params.put("TOTAL_COUNT", rows.size());

            JRBeanCollectionDataSource dataSource = new JRBeanCollectionDataSource(rows);
            JasperPrint print = JasperFillManager.fillReport(report, params, dataSource);
            return JasperExportManager.exportReportToPdf(print);
        } catch (Exception e) {
            throw new IllegalStateException("管理商品清單 PDF 產生失敗", e);
        }
    }

}
